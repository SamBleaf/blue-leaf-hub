#!/usr/bin/env node
/**
 * Create a .zip of the project with secrets redacted.
 *
 *   node scripts/export-redacted-zip.mjs
 *   node scripts/export-redacted-zip.mjs --output ~/Desktop/my-export.zip
 *   node scripts/export-redacted-zip.mjs --with-git   # include .git history
 *
 * Output default: ../blue-leaf-hub-redacted-YYYY-MM-DD.zip (next to the repo folder)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "fs";
import { basename, dirname, join, resolve } from "path";
import { fileURLToPath } from "url";
import { execSync } from "child_process";

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dir, "..");

const args = process.argv.slice(2);
const withGit = args.includes("--with-git");
const outIdx = args.indexOf("--output");
const customOut = outIdx >= 0 ? args[outIdx + 1] : null;

const date = new Date().toISOString().slice(0, 10);
const defaultZip = join(dirname(ROOT), `blue-leaf-hub-redacted-${date}.zip`);
const ZIP_PATH = customOut ? resolve(customOut) : defaultZip;

/** Paths excluded entirely from the archive */
const EXCLUDE_DIRS = new Set([
  "node_modules",
  ".git",
  "dist",
  "dev-dist",
  ".cursor",
  ".cache",
  "test-results",
  "playwright-report",
  "playwright",
  ".idea",
  ".export-redacted-tmp",
]);

const EXCLUDE_FILES = new Set([
  ".test-credentials.local",
  ".agent-test-context.local.md",
  ".DS_Store",
  "e2e/.runtime.json",
]);

const EXCLUDE_PREFIXES = [
  "e2e/report/",
];

function shouldExclude(relPath) {
  const norm = relPath.replace(/\\/g, "/");
  if (EXCLUDE_FILES.has(norm)) return true;
  for (const p of EXCLUDE_PREFIXES) {
    if (norm.startsWith(p)) return true;
  }
  if (norm.includes("__snapshots__")) return true;
  const parts = norm.split("/");
  for (const part of parts) {
    if (EXCLUDE_DIRS.has(part)) return true;
  }
  if (norm.endsWith(".cube")) return true; // server/luts
  return false;
}

/** Env keys whose values are safe to keep (non-secret config) */
const ENV_SAFE_KEYS = new Set([
  "PORT_API",
  "PORT",
  "CLAUDE_MODEL",
  "BLUEPRINT_BODY_LIMIT",
  "BLUEPRINT_REVIEW_MODEL",
  "REMINDER_CRON_ENABLED",
  "REMINDER_DAYS_BEFORE",
  "IMAP_POLL_ENABLED",
  "IMAP_POLL_INTERVAL_MS",
  "IMAP_POLL_MAX_PER_RUN",
  "SMTP_PORT",
  "SMTP_SECURE",
  "IMAP_PORT",
  "IMAP_SECURE",
  "BUILDEXACT_API_URL",
  "GMAIL_REDIRECT_URI",
  "GOOGLE_DRIVE_REDIRECT_URI",
  "DROPBOX_REDIRECT_URI",
  "DROPBOX_TEMPLATE_PATH",
  "SAM_NAME",
  "NODE_ENV",
]);

function redactEnvContent(raw) {
  const lines = raw.split("\n");
  const out = [
    "# ── REDACTED EXPORT — generated by scripts/export-redacted-zip.mjs",
    "# Replace all REDACTED values before running. Do not use this file as-is.",
    "",
  ];
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      out.push(line);
      continue;
    }
    const eq = line.indexOf("=");
    if (eq === -1) {
      out.push(line);
      continue;
    }
    const key = line.slice(0, eq).trim();
    const val = line.slice(eq + 1).trim();
    if (!val) {
      out.push(line);
      continue;
    }
    if (ENV_SAFE_KEYS.has(key)) {
      out.push(line);
      continue;
    }
    out.push(`${key}=REDACTED`);
  }
  return out.join("\n");
}

/** Redact common secret patterns in file text */
function redactTextContent(text, filePath) {
  let s = text;

  // JWT / Supabase keys
  s = s.replace(/eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g, "REDACTED_JWT");

  // Anthropic / OpenAI style keys
  s = s.replace(/sk-ant-[A-Za-z0-9_-]{20,}/g, "REDACTED_API_KEY");
  s = s.replace(/sk-[A-Za-z0-9]{20,}/g, "REDACTED_API_KEY");

  // Bearer tokens in source/docs
  s = s.replace(/Bearer\s+eyJ[A-Za-z0-9._-]+/gi, "Bearer REDACTED_JWT");

  // .env-style lines embedded in non-env files
  if (!filePath.endsWith(".env") && !filePath.endsWith(".env.example")) {
    s = s.replace(
      /^((?:[A-Z][A-Z0-9_]*)(?:_(?:KEY|SECRET|TOKEN|PASS|PASSWORD|JWT)))\s*=\s*.+$/gm,
      "$1=REDACTED"
    );
  }

  return s;
}

const TEXT_EXT = new Set([
  ".mjs", ".js", ".jsx", ".ts", ".tsx", ".json", ".md", ".sql", ".yml", ".yaml",
  ".html", ".css", ".txt", ".sh", ".env", ".example", ".toml", ".xml", ".svg",
]);

function isTextFile(name) {
  const lower = name.toLowerCase();
  if (lower === ".env" || lower.endsWith(".example")) return true;
  const dot = lower.lastIndexOf(".");
  if (dot === -1) return false;
  return TEXT_EXT.has(lower.slice(dot));
}

function copyTree(srcDir, destDir, rel = "") {
  if (rel === ".git" && !withGit) return;
  const entries = readdirSync(srcDir, { withFileTypes: true });
  for (const ent of entries) {
    const relPath = rel ? `${rel}/${ent.name}` : ent.name;
    if (shouldExclude(relPath)) continue;
    if (ent.name === ".git" && !withGit) continue;

    const src = join(srcDir, ent.name);
    const dest = join(destDir, ent.name);

    if (ent.isDirectory()) {
      mkdirSync(dest, { recursive: true });
      copyTree(src, dest, relPath);
    } else if (ent.isFile()) {
      if (ent.name === ".env") {
        const raw = readFileSync(src, "utf8");
        writeFileSync(dest, redactEnvContent(raw), "utf8");
      } else if (isTextFile(ent.name)) {
        let content = readFileSync(src, "utf8");
        content = redactTextContent(content, relPath);
        writeFileSync(dest, content, "utf8");
      } else {
        // Binary — copy as-is (images, fonts, etc.)
        execSync(`cp "${src}" "${dest}"`);
      }
    }
  }
}

function addToZip(zipPath, baseDir, folderName) {
  // Use native zip on macOS/Linux
  const cwd = dirname(baseDir);
  const name = basename(baseDir);
  execSync(`cd "${cwd}" && zip -r -q "${zipPath}" "${name}"`, { stdio: "inherit" });
}

async function main() {
  const tmpBase = join(ROOT, ".export-redacted-tmp");
  const exportDir = join(tmpBase, "blue-leaf-hub");

  console.log("\n╔══════════════════════════════════════════════════════════════╗");
  console.log("║  Blue Leaf Hub — redacted export                             ║");
  console.log("╚══════════════════════════════════════════════════════════════╝\n");

  if (existsSync(tmpBase)) rmSync(tmpBase, { recursive: true, force: true });
  mkdirSync(exportDir, { recursive: true });

  // Always ship .env.example; add redacted .env if present
  console.log("  Copying files (excluding node_modules, caches, credentials)…");
  copyTree(ROOT, exportDir);

  if (existsSync(join(ROOT, ".env"))) {
    console.log("  ✓ .env included with values redacted");
  } else {
    console.log("  - no .env found (skipped)");
  }

  if (existsSync(join(exportDir, ".env.example"))) {
    console.log("  ✓ .env.example included");
  }

  writeFileSync(
    join(exportDir, "EXPORT_README.txt"),
    `Blue Leaf Hub — redacted export
Generated: ${new Date().toISOString()}

This archive was created with scripts/export-redacted-zip.mjs.

EXCLUDED:
  - node_modules, dist, dev-dist, test artifacts, .cursor
  - .test-credentials.local, e2e/.runtime.json
  - e2e/report, playwright caches
${withGit ? "" : "  - .git (use --with-git to include)\n"}

REQUIRED FOR REVIEW ZIPS (ChatGPT / hardening exports):
  - public/brand/logo-black.png
  - public/brand/icon-blue.png
  - Synthetic sample PDFs only when BLH TEST / no real-client data
    (otherwise report local path only — exclude scripts/output/ with private data)

TEST ARTIFACT NAMING (new write tests):
  - Approved: BLH TEST via buildTestJobAddress()
  - Do NOT create new folders with __BATCH_A__, BATCHA, __E2E__, DEBUG, etc.
  - Legacy names are cleanup detection/review only
  - See docs/qa/TEST_ARTIFACT_CLEANUP_POLICY.md

REDACTED:
  - .env secret values → REDACTED (safe config keys kept)
  - JWT / API key patterns in text files

TO USE:
  1. unzip and cd into blue-leaf-hub
  2. cp .env.example .env and fill in your own credentials
  3. npm install && npm run dev

Never commit real secrets to git.
`,
    "utf8"
  );

  if (existsSync(ZIP_PATH)) rmSync(ZIP_PATH, { force: true });

  console.log(`  Creating zip → ${ZIP_PATH}`);
  addToZip(ZIP_PATH, exportDir, "blue-leaf-hub");

  rmSync(tmpBase, { recursive: true, force: true });

  const sizeMb = (statSync(ZIP_PATH).size / (1024 * 1024)).toFixed(2);
  console.log(`\n  ✓ Done: ${ZIP_PATH} (${sizeMb} MB)\n`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
