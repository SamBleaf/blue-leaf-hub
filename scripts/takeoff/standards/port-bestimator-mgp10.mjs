// Ports Sam's verified AS 1684.2 N1/N2 MGP10 tables from Bestimator (src/standards/data/*.ts) into one JSON data file
// the Hub reads: shared/takeoff/standards/data/as1684-mgp10-n1n2.js. Nothing is retyped: the typed literals are
// evaluated as they are, then written with their citations and the SHA-256 of each source file, so
// takeoff-tc-hub031 can prove the Hub's copy still equals what was ported. Re-run after Bestimator changes a table.
//   node scripts/takeoff/standards/port-bestimator-mgp10.mjs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "/Users/samuelmorris/Desktop/Bestimator.nosync/scope agent ai/src/standards/data";
const FILES = [
  ["lintels-mgp10.ts", ["T17_MGP10", "T18_MGP10", "T47_MGP10", "T48_MGP10"]],
  ["jamb-studs-mgp10.ts", ["T11_MGP10_JAMBS"]],
  ["studs-mgp10.ts", ["T7_MGP10_STUDS", "T36_MGP10_STUDS"]],
];
const tables = {};
const sources = {};
for (const [file, names] of FILES) {
  const text = readFileSync(`${SRC}/${file}`, "utf8");
  sources[file] = createHash("sha256").update(text).digest("hex");
  const js = text.replace(/^import .*$/gm, "").replace(/export const (\w+): \w+ =/g, "const $1 =");
  const got = new Function(`${js}\nreturn { ${names.join(", ")} };`)();
  for (const n of names) tables[n.split("_")[0]] = got[n];
}
const out = {
  _about: "AS 1684.2 N1/N2 Supplement 4 (2006), Stress Grade MGP10, single/upper and lower storey tables as transcribed and verified in Bestimator (position-parsed from Sam's licensed PDF, then read against the rendered page cell by cell). Sam's licensed extract; the Hub repo is private. Generated by scripts/takeoff/standards/port-bestimator-mgp10.mjs: do not hand-edit values.",
  source: { pdf: "~/Documents/AS 1684 Span Tables/Non-cyclonic/N1N2/MGP10.PDF", standard: "AS 1684.2 N1/N2 Supplement 4", edition: "2006", grade: "MGP10", wind: ["N1", "N2"],
    portedFrom: "Bestimator src/standards/data/*.ts", sha256: sources },
  tables,
};
writeFileSync(new URL("../../../shared/takeoff/standards/data/as1684-mgp10-n1n2.js", import.meta.url),
  `// GENERATED by scripts/takeoff/standards/port-bestimator-mgp10.mjs from Bestimator's verified tables. Do not hand-edit values.\nexport default ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.entries(tables).map(([k, t]) => `${k}: ${t.rows.length} rows, ${t.columns.length} columns, verified=${t.verified}, page ${t.citation.page}`).join("\n"));
