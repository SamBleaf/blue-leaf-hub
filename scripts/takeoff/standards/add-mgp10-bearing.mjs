// One-off patch on the ported MGP10 data (run after port-bestimator-mgp10.mjs): reads the PDF subscript-aware, corrects the
// rows and cells the port dropped or fused (T48 170x35 was 9005, really 900 + 5 mm bearing) and adds extraBearingMm to every row of T17/T18/T47/T48.
// Idempotent. Refuses to change any span except a fused one. node scripts/takeoff/standards/add-mgp10-bearing.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { readPage } from "./pdf-lintel-rows.mjs";

const FILE = new URL("../../../shared/takeoff/standards/data/as1684-mgp10-n1n2.js", import.meta.url);
const src = readFileSync(FILE, "utf8");
const data = JSON.parse(src.slice(src.indexOf("export default ") + 15).replace(/;\s*$/, ""));
let added = 0, fixed = 0, withBearing = 0;
for (const id of ["T17", "T18", "T47", "T48"]) {
  const t = data.tables[id];
  const found = readPage(t.citation.page);
  // rows the original port dropped (they carry subscripts the old parse could not read): add them from the PDF
  const have = new Set(t.rows.map((r) => r.size));
  for (const [size, cells] of found) {
    if (have.has(size)) continue;
    if (!cells || cells.spans.length !== t.columns.length) throw new Error(`${id} ${size}: row not readable from the PDF`);
    const m = /^(?:(\d)\/)?(\d+)x(\d+)$/.exec(size);
    t.rows.push({ size, plies: m[1] ? +m[1] : 1, depthMm: +m[2], breadthMm: +m[3], maxSpanMm: cells.spans });
    added++;
  }
  for (const r of t.rows) {
    const pdf = found.get(r.size);
    if (!pdf || pdf.spans.length !== r.maxSpanMm.length) throw new Error(`${id} ${r.size}: row not readable from the PDF`);
    pdf.spans.forEach((v, i) => {
      if (r.maxSpanMm[i] !== v) {
        if (r.maxSpanMm[i] === +`${v}${pdf.extra[i]}`) { r.maxSpanMm[i] = v; fixed++; } else throw new Error(`${id} ${r.size} cell ${i}: Hub ${r.maxSpanMm[i]} vs PDF ${v}`);
      }
    });
    r.extraBearingMm = pdf.extra;
    withBearing += pdf.extra.filter(Boolean).length;
  }
}
data._about = data._about.replace(/ Generated by/, " Extra bearing (the PDF's subscript, mm beyond 35) is read from the PDF by add-mgp10-bearing.mjs. Generated by");
writeFileSync(FILE, `// GENERATED by scripts/takeoff/standards/port-bestimator-mgp10.mjs from Bestimator's verified tables, then add-mgp10-bearing.mjs (extraBearingMm). Do not hand-edit values.\nexport default ${JSON.stringify(data, null, 1)};\n`);
console.log(`added ${added} row(s) the port had dropped; fixed ${fixed} fused cell(s); ${withBearing} cells carry extra bearing`);
